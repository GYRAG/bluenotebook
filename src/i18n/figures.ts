/** Words the triangle stamp is built from ("isosceles right triangle"). */
const WORDS: Record<string, string> = {
  'ტოლგვერდა': 'equilateral', 'ტოლფერდა': 'isosceles', 'სხვადასხვაგვერდა': 'scalene',
  'მართკუთხა': 'right', 'ბლაგვკუთხა': 'obtuse', 'მახვილკუთხა': 'acute', 'სამკუთხედი': 'triangle',
};

const look = (s: string) => FIG_EN[s] ?? CLIENT_EN[s];
/** A figure string in the given language. */
export const tfIn = (lang: Lang, s: string) => (lang === 'en' ? look(s) ?? s : s);
/** A figure string in the page's language (browser). */
export const tf = (s: string) => tfIn(pageLang(), s);
/** A stamp name: a known name, or a phrase built word by word; a "why" built from ", "-joined parts. */
export function tfPhrase(s: string): string {
  if (pageLang() !== 'en') return s;
  const known = look(s);
  if (known) return known;
  if (s.includes(', ')) return s.split(', ').map(tf).join(', ');
  const w = s.split(' ').map(x => WORDS[x] ?? x).join(' ');
  return w.charAt(0).toUpperCase() + w.slice(1);
}
